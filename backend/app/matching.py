"""Matching logic. STUB: tag overlap instead of embeddings.

Owner of the core replaces `fit()` with embedding-based closeness and the
explanation/icebreaker with precomputed LLM text. The shape of `recommend()`
must stay the same (see docs/CONTRACT.md).

score(A, B) = sqrt(fit(A->B) * fit(B->A))
"""
import math
import time

from .models import RECIPROCAL, Match, Profile, ProfileIn


def _tags(p: ProfileIn) -> set[str]:
    return {t.lower() for t in (*p.stack, *p.interests)}


def fit(a: ProfileIn, b: Profile) -> float:
    """How well B serves A's goal. 0 if goals are not reciprocal."""
    if RECIPROCAL[a.goal] != b.goal:
        return 0.0
    ta, tb = _tags(a), _tags(b)
    union = ta | tb
    overlap = len(ta & tb) / len(union) if union else 0.0
    return 0.15 + 0.85 * overlap  # baseline keeps reciprocal pairs above zero


def score(a: ProfileIn, b: Profile) -> float:
    fa = fit(a, b)
    fb = fit(b, Profile(id="viewer", **a.model_dump()))
    return math.sqrt(fa * fb)


def _texts(a: ProfileIn, b: Profile, lang: str) -> tuple[str, str, str, str]:
    shared = sorted(_tags(a) & _tags(b))
    tags = ", ".join(shared) if shared else "-"
    # TODO: real text per language, generated by LLM and cached.
    you_give = f"[stub] Your experience: {a.role}."
    they_give = f"[stub] Their side: {b.role}."
    explanation = f"[stub] You both work with: {tags}."
    icebreaker = f"[stub] Hi {b.name.split()[0]}! I saw you work on {tags}."
    return you_give, they_give, explanation, icebreaker


def recommend(
    viewer: ProfileIn,
    profiles: list[Profile],
    lang: str = "ru",
    penalties: dict[str, float] | None = None,
    viewer_id: str | None = None,
) -> tuple[int, list[Match]]:
    start = time.perf_counter()
    penalties = penalties or {}
    scored: list[tuple[float, Profile]] = []
    for p in profiles:
        if viewer_id and p.id == viewer_id:
            continue
        s = score(viewer, p) * penalties.get(p.id, 1.0)
        if s > 0:
            scored.append((s, p))
    scored.sort(key=lambda x: x[0], reverse=True)

    matches: list[Match] = []
    for s, p in scored[:5]:
        you_give, they_give, explanation, icebreaker = _texts(viewer, p, lang)
        matches.append(
            Match(
                profile=p,
                score=round(s, 3),
                shared_tags=sorted(_tags(viewer) & _tags(p)),
                you_give=you_give,
                they_give=they_give,
                explanation=explanation,
                icebreaker=icebreaker,
            )
        )
    took_ms = int((time.perf_counter() - start) * 1000)
    return took_ms, matches
